CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    phone VARCHAR(30) DEFAULT NULL,
    saldo NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    role VARCHAR(20) NOT NULL DEFAULT 'client',
    status VARCHAR(20) NOT NULL DEFAULT 'approved',
    register_ip VARCHAR(64) DEFAULT NULL,
    last_ip VARCHAR(64) DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.configuracoes (
    chave VARCHAR(100) PRIMARY KEY,
    valor TEXT
);

CREATE TABLE IF NOT EXISTS public.atestados (
    id VARCHAR(50) PRIMARY KEY,
    user_id BIGINT,
    user_nome VARCHAR(150),
    paciente_nome VARCHAR(150),
    cpf VARCHAR(30),
    cns VARCHAR(30),
    medico_nome VARCHAR(150),
    crm VARCHAR(50),
    cid VARCHAR(50),
    dias_repouso INT,
    unidade_saude VARCHAR(255),
    valor_cobrado NUMERIC(10,2) DEFAULT 10.00,
    dados_json TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.cnhs (
    id VARCHAR(50) PRIMARY KEY,
    user_id BIGINT,
    user_nome VARCHAR(150),
    nome_cnh VARCHAR(150),
    cpf VARCHAR(30),
    rg VARCHAR(50),
    categoria VARCHAR(20) DEFAULT 'B',
    genero VARCHAR(20) DEFAULT 'Feminino',
    valor_cobrado NUMERIC(10,2) DEFAULT 25.00,
    valor_pendencia VARCHAR(50) DEFAULT '500,00',
    dados_json TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.exames (
    id VARCHAR(50) PRIMARY KEY,
    user_id BIGINT,
    user_nome VARCHAR(150),
    paciente_nome VARCHAR(150),
    cpf VARCHAR(30),
    resultado VARCHAR(20) DEFAULT 'Negativo',
    laboratorio VARCHAR(150),
    data_coleta DATE,
    data_laudo DATE,
    valor_cobrado NUMERIC(10,2) DEFAULT 20.00,
    dados_json TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.recargas (
    id VARCHAR(50) PRIMARY KEY,
    user_id BIGINT,
    user_nome VARCHAR(150),
    valor NUMERIC(10,2) NOT NULL,
    metodo VARCHAR(50) DEFAULT 'PIX QrCode',
    status VARCHAR(20) DEFAULT 'pending',
    comprovante TEXT,
    data TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.indicacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicador_id BIGINT,
    indicador_nome VARCHAR(150),
    indicador_email VARCHAR(150),
    indicado_id BIGINT,
    indicado_nome VARCHAR(150),
    indicado_email VARCHAR(150),
    bonus_recebido NUMERIC(10,2) DEFAULT 0.00,
    status VARCHAR(20) DEFAULT 'pendente',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.atividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    user_nome VARCHAR(150),
    tipo VARCHAR(50),
    descricao TEXT,
    sub_rotulo VARCHAR(150),
    valor NUMERIC(10,2) DEFAULT 0.00,
    tag_class VARCHAR(50),
    tag_text VARCHAR(50),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- HABILITAR RLS COM POLÍTICAS DE ACESSO LIVRE PARA O FRONTEND VERCEL
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.configuracoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.atestados ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cnhs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exames ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.recargas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.indicacoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.atividades ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    DROP POLICY IF EXISTS "Anon acesso completo usuarios" ON public.usuarios;
    CREATE POLICY "Anon acesso completo usuarios" ON public.usuarios FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    
    DROP POLICY IF EXISTS "Anon acesso completo configuracoes" ON public.configuracoes;
    CREATE POLICY "Anon acesso completo configuracoes" ON public.configuracoes FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    
    DROP POLICY IF EXISTS "Anon acesso completo atestados" ON public.atestados;
    CREATE POLICY "Anon acesso completo atestados" ON public.atestados FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    
    DROP POLICY IF EXISTS "Anon acesso completo cnhs" ON public.cnhs;
    CREATE POLICY "Anon acesso completo cnhs" ON public.cnhs FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    
    DROP POLICY IF EXISTS "Anon acesso completo exames" ON public.exames;
    CREATE POLICY "Anon acesso completo exames" ON public.exames FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    
    DROP POLICY IF EXISTS "Anon acesso completo recargas" ON public.recargas;
    CREATE POLICY "Anon acesso completo recargas" ON public.recargas FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    
    DROP POLICY IF EXISTS "Anon acesso completo indicacoes" ON public.indicacoes;
    CREATE POLICY "Anon acesso completo indicacoes" ON public.indicacoes FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    
    DROP POLICY IF EXISTS "Anon acesso completo atividades" ON public.atividades;
    CREATE POLICY "Anon acesso completo atividades" ON public.atividades FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
END $$;
